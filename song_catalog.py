"""Song metadata shared by the bank compiler and the Unity inspector/player.

Run python song_catalog.py after editing SONGS to refresh the Unity source.
The ordinal is serialized in scenes, and the key is persisted in layout files.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import json


@dataclass(frozen=True)
class Song:
    ordinal: int
    key: str
    title: str
    duration_ms: int
    harmony: bool = True
    folder_title: str | None = None

    @property
    def bank(self):
        return "UpmixStems" if self.ordinal == 0 else "Stems_" + self.key

    @property
    def suffix(self):
        return "" if self.ordinal == 0 else "_" + self.key


SONGS = (
    Song(0, "WoBuNanGuo", "我不难过", 320400),
    Song(1, "SeeYouAgain", "See You Again", 229525),
    Song(2, "GloriousYears", "光辉岁月", 298560),
    Song(3, "SmokeOnTheWater", "Smoke on the Water", 341426),
    Song(4, "FiveHundredMiles", "Five Hundred Miles", 207453),
    Song(5, "ShuoSanJiuSan", "说散就散", 242625),
    Song(6, "FurElise", "致爱丽丝", 180240, harmony=False, folder_title="《致爱丽丝》"),
    Song(7, "XiangShanSheGu", "香山射鼓", 274239, harmony=False),
)

UNITY_SOURCE = Path(__file__).resolve().parent / "WwiseUpmix/Assets/SpatialStemPlayer.Songs.cs"


def unity_source():
    def literal(value):
        return json.dumps(value, ensure_ascii=False)

    enums = []
    entries = []
    for index, song in enumerate(SONGS):
        if index != song.ordinal:
            raise ValueError(f"Expected serialized ordinal {index} for {song.key}")
        title = literal(song.title)
        enums.append(f"        [InspectorName({title})] {song.key} = {song.ordinal},")
        fields = (title, str(song.duration_ms), literal(song.bank), literal(song.suffix),
                  str(song.harmony).lower())
        entries.append(f"        new SongInfo({', '.join(fields)}),")
    return """// Generated by song_catalog.py. Edit SONGS and regenerate.
using UnityEngine;

public sealed partial class SpatialStemPlayer
{
    private enum Song
    {
""" + "\n".join(enums) + """
    }

    private static readonly SongInfo[] Songs =
    {
""" + "\n".join(entries) + """
    };
}
"""


if __name__ == "__main__":
    UNITY_SOURCE.write_text(unity_source(), encoding="utf-8")
